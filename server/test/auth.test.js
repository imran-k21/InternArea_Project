const test = require("node:test");
const assert = require("node:assert/strict");

process.env.ADMIN_TOKEN_SECRET = "test-secret-with-at-least-32-characters-long";
const { createAdminToken, verifyAdminToken } = require("../Middleware/auth");

test("admin token generated by the server is accepted", () => {
  const token = createAdminToken("admin");
  assert.equal(verifyAdminToken(token), true);
});

test("tampered admin tokens are rejected", () => {
  const token = createAdminToken("admin");
  const tampered = `${token.slice(0, -1)}x`;
  assert.equal(verifyAdminToken(tampered), false);
});

test("missing and malformed admin tokens are rejected", () => {
  assert.equal(verifyAdminToken(""), false);
  assert.equal(verifyAdminToken("not-a-token"), false);
});
